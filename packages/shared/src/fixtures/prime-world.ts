import type { JsonObject, PrimeWorldDetail, PrimeWorldEdge, PrimeWorldNode, WorldView } from "../types/prime-world.js";

const edge = (id: string, kind: PrimeWorldEdge["kind"], sourceNode: string, sourcePort: string, targetNode: string, targetPort: string): PrimeWorldEdge => ({ id, kind, source: { nodeId: sourceNode, port: sourcePort }, target: { nodeId: targetNode, port: targetPort } });
const node = (id: string, type: string, config: PrimeWorldNode["config"] = {}): PrimeWorldNode => ({ id, type, version: 1, config });
const baseView = (title: string, input: "text" | "voice" | "text-and-voice"): WorldView => ({
  revision: 0,
  title,
  root: {
    id: "root",
    type: "stack" as const,
    children: [
      { id: "narrative", type: "text" as const, text: "", tone: "body" as const },
      {
        id: "choices",
        type: "choices" as const,
        actionId: "choose",
        choices: [
          { id: "begin", label: "开始" },
          { id: "observe", label: "观察四周" },
          { id: "wait", label: "稍作等待" },
        ],
      },
    ],
  },
  input: { mode: input, placeholder: "你准备怎么做？" },
  audio: { autoPlay: true, allowInterrupt: true },
});

